// obfuscator.js

const {
  hideConstants
} = require("./constant-hider");

const {
  solveMath
} = require("./math-solver");

const {
  compileSimple
} = require("./vm-compiler");

function obfuscate(source, options = {}) {
  if (typeof source !== "string") {
    throw new TypeError(
      "Source must be a string"
    );
  }

  let code =
    source.replace(/\r\n?/g, "\n");

  const stats = {
    strings: 0,
    numbers: 0,
    booleans: 0,
    vm: false,
    instructions: 0,
    constants: 0
  };

  /*
   * Math solver
   */
  if (options.solveMath !== false) {
    code = solveMath(code);
  }

  /*
   * Constant hiding
   *
   * No constant table indexing.
   */
  if (options.hideConstants !== false) {
    const result =
      hideConstants(code);

    code = result.source;

    stats.strings =
      result.counts.strings;

    stats.numbers =
      result.counts.numbers;

    stats.booleans =
      result.counts.booleans;

    if (result.header) {
      code =
        result.header +
        "\n\n" +
        code;
    }
  }

  /*
   * Optional VM compilation.
   *
   * We expose the generated bytecode as metadata
   * rather than silently replacing arbitrary Luau
   * with an incomplete VM.
   */
  let vmData = null;

  if (options.vm === true) {
    vmData =
      compileSimple(source);

    stats.vm = true;
    stats.instructions =
      vmData.instructions.length;

    stats.constants =
      vmData.constants.length;
  }

  const banner =
    "-- Generated by Luau Obfuscator\n" +
    "-- Local source transformer\n";

  if (stats.vm) {
    return {
      code:
        banner +
        "\n" +
        code,

      stats,

      vm: vmData
    };
  }

  return {
    code:
      banner +
      "\n" +
      code,

    stats
  };
}

module.exports = {
  obfuscate
};
